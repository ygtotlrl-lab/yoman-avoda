#!/usr/bin/env node
/*  test_caps_ui.mjs — חלק «מסך ועיצוב» של בודק היכולות.
 *
 *  **מה נאכף:** ⛔ שורות טבלת התשתית שבקטגוריות «ו» ו«ז» — ⚠️ כל תא מול
 *  ה-probe שלו, בשני הכיוונים: ⭐ ✅ שה-probe אינו מוצא **מפיל**, ⛔ ו-❌
 *  שהוא כן מוצא מפיל גם כן. ⚠️ השיוך נגזר מאות הקטגוריה שבטבלה ⛔ ואינו
 *  מוקלד לפי מספר שורה.
 *
 *  **הנימוק המדוד:** בודק היכולות היה שער אחד ארוך, ⛔ ורתמות המוטציה
 *  מריצות אותו עשרות פעמים בכל סבב — ⚠️ והזמן נגזר **ממספרן** ולא מגודל
 *  הקוד: ⭐ נמדד `test_rulesdocs` 102 שניות ו-`test_matrix` 67, ⛔ והסט
 *  כולו נעצר על שער אחד.
 *
 *  **מה יישבר בלעדיו:** ⛔ הבריכה מריצה ארבעה תהליכים, ⚠️ ושער שאורכו
 *  כשליש מהסט חוסם אותה: ⭐ שלושת האחרים מסיימים וממתינים לו.
 *
 *  **מה אינו נאכף כאן:** ⛔ שורות שאינן בקטגוריות האלה — ⚠️ כל אחת נמדדת
 *  בחלק שלה, ⛔ ואין שורה בשני חלקים.
 *
 *  ⛔ אינו ניתן למוטציה — ⚠️ גופו הוא קריאה אחת לבודק המשותף, ⭐ והמנגנון
 *  שהוא מפעיל ממוטט ב-`test_matrix`, שהוא היחיד שמהפך תאים.
 *  ⛔ הקובץ זהה בית-לבית בארבעת הריפו — אין בו בלוק `APP`.
 */

/*  ⛔ הקובץ הזה אינו אוכף שורה בטבלת התשתית (סבב 72) — ⚠️ הצהרה ריקה
 *  ולא היעדר: ⛔ שער בלי הצהרה אינו נבדל משער שההצהרה שלו נשמטה. */
export const ROWS = [];

/*  ⛔ שער מריץ את כל טענותיו — ⚠️ תהליך שנסגר באמצע מדפיס «עבר» על טענות
 *  שלא רצו: ⭐ `EXPECTED` הוא רצפה שנמדדה ברמה שבה השער רץ, ⛔ ופחות ממנה
 *  הוא כשל — ⚠️ והמאזין על `exit` תופס גם יציאה שקדמה להמתנה. */
const GATE_ID = new URL(import.meta.url).pathname.split('/').pop();
/*  ⛔ ריצפת הטענות — ⚠️ **מה נכנס**: המשותפת, שהיא מספר זהה בארבעת הריפו,
 *  ⛔ והפרטית עם היכולת שמוסיפה אותה; ⛔ **ומה מפיל**: משותפת שנבדלת בין
 *  הריפו, פרטית בלי נימוק, וסכום אפס. ⭐ **ולמה לא מספר אחד**: הוא מסתיר
 *  טענה משותפת שאבדה.
 *  ⚠️ **וכאן אין ריצפה פרטית** — ⛔ מספר השורות בקטגוריה נגזר מהטבלה,
 *  ⭐ והטבלה משותפת בית-לבית: כל תא מוסיף טענה אחת בכל אחת מהארבע. */
const FLOOR = { shared: 32, app: 0, appWhy: '' };
const EXPECTED = FLOOR.shared + FLOOR.app;
let RAN = 0;
/*  ⛔ המונה נלכד בכניסה לשלב המוטציות (סבב 119) — ⚠️ `null` הוא תהליך
 *  שלא הגיע לשם, ⛔ ואפס הוא שער שכל גופו מוטציות: ⭐ ההבחנה היא מה
 *  שמבדיל ריצה חלקית מדילוג מוצהר. */
let PRE_MUT = null;
/*  ⛔ הדגל נלכד ברישום ⛔ ולא בסגירה — ⚠️ שער שמריץ שער אחר מציב אותו
 *  **אחרי** הרישום, ⭐ ולכן הוא חל על הילד ⛔ ולא על עצמו. */
const SUBRUN = !!process.env.GATE_SUBRUN;
/*  ⛔ הריצפה נמדדת בשני הכיוונים (סבב 118) — ⚠️ **מה נכנס**: מספר הטענות
 *  שרצו עד שלב המוטציות; ⛔ **ומה מפיל**: פחות מהמוצהר — ריצה חלקית —
 *  ⛔ ויותר ממנו — ריצפה מיושנת. ⭐ **ולמה שני הכיוונים**: ריצפה שאינה
 *  מתעדכנת מפסיקה למדוד את מה שנוסף. ⚠️ ושער שמספרו משתנה גם בלי
 *  המוטציות מוכרז ב-`APP.floorRange` ומקבל את הטווח ב-`GATE_FLOOR_RANGE`. */
const FLOOR_MAX = (() => {
  const r = /^(\d+)-(\d+)$/.exec(process.env.GATE_FLOOR_RANGE || '');
  return r ? Number(r[2]) : EXPECTED;
})();
process.on('exit', () => {
  /*  ⚠️ שער שיובא לתהליך של שער אחר אינו סוגר — ⛔ הספירה שלו לא רצה.
   *  ⛔ וגם ריצת-משנה מוצהרת אינה סוגרת — ⚠️ שער שמריץ את עצמו בעץ
   *  סינתטי מגיע לחלק מטענותיו בכוונה, ⭐ והרצפה נמדדת על עץ אמיתי. */
  if (!process.argv[1] || !process.argv[1].endsWith(GATE_ID)) return;
  if (SUBRUN) return;
  if (PRE_MUT === 0 && process.env.GATE_MUT !== '1') {
    console.log(`⏭ ${GATE_ID}: כל גופו רץ ברמה המלאה — לא נמדד כאן`);
    return;
  }
  const N = PRE_MUT || RAN;
  console.log(`רצו ${N} מתוך ${EXPECTED}`);
  if (N < EXPECTED) {
    console.error(`❌ ${GATE_ID}: רצו ${N} טענות מתוך ${EXPECTED} מוצהרות — ` +
      'מה עושים: ודא `await` בקריאה הראשית, ⛔ ויציאה שאינה קודמת להמתנה.');
    process.exitCode = 1;
  } else if (N > FLOOR_MAX) {
    console.error(`❌ ${GATE_ID}: רצו ${N}, והריצפה ${EXPECTED} — ` +
      'עדכן את `FLOOR`.');
    process.exitCode = 1;
  }
});

/*  ⛔ `CAP_INPROC` נקבע **לפני** הייבוא — ⚠️ בלעדיו גוף הבודק סוגר את
 *  התהליך בעצמו על חלק הליבה, ⭐ וחלק זה לא היה רץ כלל. */
process.env.CAP_INPROC = '1';
const { run, ranOf } = await import('./check-capabilities.mjs');
const failures = run(null, null, 'test_caps_ui');
RAN += ranOf();
process.exit(failures ? 1 : 0);
