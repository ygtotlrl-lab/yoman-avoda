/*  ⛔ הסדר קנוני ⛔ ואינו אלפביתי — ⚠️ הוא סדר עמודות טבלת התשתית, ⭐ ושער
 *  שמצליב עמודה לאפליקציה נשען עליו: ⛔ סדר אחר כאן מזיז כל תא. */
export const PEERS = ['yoman-avoda', 'hanhala-ruchanit', 'schar-limud', 'gius'];

/*  ⛔ ה-`scope` נגזר מהשם ⛔ ואינו מוקלד — ⚠️ ערך יחסי נפתר לכתובת מוחלטת,
 *  ⭐ ובכולן זה אותו origin: ⛔ והדפדפן ראה אפליקציה אחת. */
export const appScope = (slug) => '/' + slug + '/';

/*  ⛔ הזוגות נגזרים ⛔ ואינם רשימה שנייה — ⚠️ **מה נכנס**: שם ⟵ ה-`scope`
 *  שנגזר ממנו; ⛔ **ומה מפיל**: אין כאן מה שיפיל, ⭐ שאין כאן הכרעה.
 *  ⚠️ **ולמה המבנה קיים**: שני קוראים בונים את אותו זוג, ⛔ ושתי בנייות
 *  לאותו זוג הן שתי הזדמנויות להיבדל. */
export const APP_SCOPES = PEERS.map((slug) => [slug, appScope(slug)]);

/*  ⛔ מספר עמודות האפליקציה בטבלת התשתית נגזר מהמרשם ⛔ ואינו מוקלד —
 *  ⚠️ שורה בטבלה היא `| # | שם | מה זה | <עמודה לכל אפליקציה> | הערה |`,
 *  ⭐ ופיצולה ב-`|` מחזיר תא ריק בכל קצה: ⛔ מי שמקליד את המספרים האלה
 *  שובר את כל מפרקי הטבלה ביום שבו נוספת אפליקציה. */
export const COL_FIRST = 4;
export const COL_LAST = COL_FIRST + PEERS.length - 1;
export const COL_NOTE = COL_LAST + 1;
export const ROW_CELLS = COL_NOTE + 2;
export const APP_COLS = PEERS.map((s, i) => COL_FIRST + i);
