-- ────────────────────────────────────────────────────────────────────────────
-- 1. שתי העמודות
-- ────────────────────────────────────────────────────────────────────────────
-- ⚠️ `default false` הוא מה שהופך את הקובץ לבטוח על טבלה שכבר יש בה
--    שורות: כל רשומת יומן קיימת הופכת ל-`archived=false`, שזו בדיוק
--    המשמעות שלה. ⛔ ו-`not null` נדרש כדי שהשליפה המסוננת
--    (`.eq('archived', …)`) לא תפספס שורות עם `null` — שלושה מצבים
--    לעמודה בוליאנית הם בדיוק הדרך שבה שורה נעלמת בשקט משני צדי הסינון.
alter table public.tb_entries
  add column if not exists archived boolean not null default false;

-- ⚠️ `gdate` הייתה עמודה של `tb_archive` בלבד. היא נוספת כאן כדי שהעברת
--    השורה ב-`005` תהיה **מלאה** ולא חלקית: שורה שמאבדת עמודה בהעברה
--    מחייבת שחזור-מהנתונים בנתיב החזרה במקום העתקה. ⚠️ היא נשארת `null`
--    לרשומות יומן, ו⛔ אין לגזור אותה מ-`data->>'gdate'` בטריגר — מקור
--    אמת שני לאותו ערך הוא בדיוק מה ש-`002` נמנע ממנו כשהשאיר את גוף
--    הרשומה ב-`data`.
alter table public.tb_entries
  add column if not exists gdate text;


-- ────────────────────────────────────────────────────────────────────────────
-- 2. האינדקס שתומך בשליפה המסוננת
-- ────────────────────────────────────────────────────────────────────────────
-- ⛔ **אינדקס מלא ולא חלקי** (הלקח מ-`migrations/007` של schar-limud, וכפי
--    שכבר נרשם ב-`002`): אינדקס עם `WHERE` שובר את הסקת `ON CONFLICT`,
--    ו-PostgREST אינו יכול לצרף את התנאי — כל `upsert` נופל ב-42P10
--    והשמירה מפסיקה לעבוד. ⚠️ הפיתוי כאן ממשי דווקא מפני שהשאילתה
--    מסננת על ערך אחד (`archived=false`), ו-`where archived = false`
--    נראה כמו האינדקס הנכון. ⛔ הוא אינו.
create index if not exists tb_entries_yeshiva_archived_key
  on public.tb_entries (yeshiva, archived, rec_key);
create index if not exists tb_entries_yeshiva_archived_updated_idx
  on public.tb_entries (yeshiva, archived, updated_at desc);

-- ⚠️ האינדקס הייחודי הקיים `(yeshiva, rec_key)` **נשאר כפי שהוא ואינו
--    כולל את `archived`.** זה מכוון, והוא מה שאוכף את ההנחה שעליה `005`
--    נשען: מרחב המפתחות של שני הסוגים **זר** — `entryKey` מחזירה מזהה
--    מספרי, ו-`archiveKey` מחזירה `g:…`/`i:…`. ⛔ הוספת `archived`
--    לאינדקס הייחודי הייתה מתירה לאותו `rec_key` להתקיים פעמיים באותו
--    מוסד, כלומר מבטלת בדיוק את ההתנגשות ש-`005` בודק ומדווח עליה.


