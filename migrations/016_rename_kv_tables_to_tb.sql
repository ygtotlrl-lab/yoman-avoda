-- ============================================================================
-- 016_rename_kv_tables_to_tb.sql — תחילית הבעלים לטבלאות ההגדרות של היומן
-- ============================================================================
--
-- ⛔ **רצה במסד** — ⚠️ הוחלה בסבב 144 ואומתה: ספירת השורות זהה למה שהיה,
--    ⛔ ואפס שמות ישנים ב-`pg_class` ובגוף שתי הפונקציות.
--
-- ⛔⛔ **מה הקובץ עושה:** ⚠️ מסב את `kv_rishon` ל-`tb_kv_rishon` ואת
--    `kv_ramataviv` ל-`tb_kv_ramataviv` — ⭐ ושומר נתונים, אינדקסים,
--    אילוצים ומדיניות RLS: ⛔ `rename` אינו העתקה.
--
-- ⛔⛔ **הנימוק:** ⚠️ כל טבלה במסד נושאת את תחילית בעליה — `tb_` ליומן ·
--    `ys_` להנהלה · `sl_` לשכר · `g_` לגיוס · `sh_` למשותף; ⭐ ושתי
--    הטבלאות האלה נשאו תחילית של מנגנון (`kv_`) ולא של בעלים: ⛔ ומי
--    שקורא את רשימת הטבלאות אינו יודע למי הן שייכות.
--
-- ⛔ **ומכשיר שלא עודכן נכשל בסנכרון עד שיעדכן** — ⚠️ האפליקציה
--    מקומית-תחילה, ⭐ והנתונים ממתינים במכשיר ועולים בעדכון: ⛔ אין כאן
--    אובדן, ⚠️ ויש חלון.
--
-- ⛔ **אידמפוטנטי** — ⚠️ ההסבה רצה רק אם השם הישן עדיין קיים.
--
-- ============================================================================

do $$
begin
  if to_regclass('public.kv_rishon') is not null
     and to_regclass('public.tb_kv_rishon') is null then
    alter table public.kv_rishon rename to tb_kv_rishon;
  end if;
  if to_regclass('public.kv_ramataviv') is not null
     and to_regclass('public.tb_kv_ramataviv') is null then
    alter table public.kv_ramataviv rename to tb_kv_ramataviv;
  end if;
end $$;
