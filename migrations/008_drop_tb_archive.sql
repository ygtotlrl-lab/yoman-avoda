-- ⛔ **`drop` ולא `truncate`, ובלי `cascade`** — ⚠️ `cascade` היה מפיל
--    בשקט כל תלות שלא ידענו עליה: ⭐ אם קיימת כזו, ⛔ עדיף שההרצה תיפול
--    ותאלץ להבין מהי.
--
-- ⛔ **וזו החריגה היחידה מ«אין `DELETE` פיזי»** — ⚠️ הכלל חל על **רשומות**
--    ולא על טבלה שכל תוכנה הועתק: ⭐ מחיקה רכה מגינה על נתון שאפשר לאבד,
--    ⛔ וכאן אין נתון לאבד.
--
-- ⛔ **אידמפוטנטי** — `if exists`, ⚠️ והרצה חוזרת אינה משנה דבר.
