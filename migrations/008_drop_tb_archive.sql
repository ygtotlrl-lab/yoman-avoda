-- ⛔ **המחיקה נעשתה אחרי מדידה ולא לפניה** — ⭐ נמדד לפני ההרצה:
--    **כל 173 שורותיה קיימות ב-`tb_entries`** עם `archived=true`,
--    ⛔ **ואפס שורות ייחודיות לה**. ⚠️ «אין לה קוראים» לבדו לא היה מספיק:
--    ⛔ שורה שקיימת רק כאן הייתה יורדת איתה, ⭐ ואין ממה לשחזר.
