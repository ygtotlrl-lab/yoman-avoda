update tb_entries
   set updated_at = (extract(epoch from synced_at) * 1000)::bigint
 where (updated_at is null or updated_at = 0)
   and synced_at is not null;

-- ⛔ שורה בלי `synced_at` **וגם** בלי חותמת אינה מקבלת ערך מומצא — ⚠️ אין
--    עבורה שום זמן שנמדד, ⭐ ומוטב שתישאר גלויה כחריגה ⛔ מאשר שתקבל תאריך
--    שלא היה. ⚠️ נמדד: אפס שורות כאלה.
