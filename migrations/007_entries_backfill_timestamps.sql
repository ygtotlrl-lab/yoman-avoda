-- ============================================================================
-- 007_entries_backfill_timestamps.sql — חותמת לרשומות שנכתבו בלעדיה
-- ============================================================================
--
-- ⛔ **רץ במסד.** ⛔ מיגרציה שכבר רצה אינה נערכת — ⚠️ המסד החיל אותה,
--    ועריכה שלה יוצרת מצב שבו הקובץ מתאר משהו אחר ממה שרץ; ⛔ שינוי מבני
--    נעשה בקובץ הבא בתור.
--
-- ⭐ **מה משתנה:** 157 רשומות ארכיון שנכתבו בהעברה מ-`kv` נשאו
--    `updated_at` ריק. ⛔ אפס אינו «לא ידוע» אלא «הישן ביותר», ⚠️ ולכן
--    **כל** עריכה מנצחת אותן במיזוג — ⛔ גם עריכה שגויה, ⛔ וגם מכשיר
--    ששעונו נסחף. ⭐ הכשל שקט לחלוטין: המיזוג עובד בדיוק כפי שנכתב.
--
-- ⚠️ **שני מקורות, ולא אחד** — ⛔ והבחירה ביניהם היא מה שמונע חותמת
--    שהומצאה:
--    ⭐ ל-67 רשומות ה-`id` שבתוך `data` הוא **מילישניות** — ⭐ זמן היצירה
--       האמיתי במכשיר, ⛔ והוא הערך הנכון ביותר שיש.
--    ⚠️ ל-90 הנותרות ה-`id` הוא **מספר רץ** ולא זמן — ⛔ המרתו לחותמת
--       הייתה מציבה אותן ב-1970, ⚠️ כלומר בדיוק הבעיה שהמיגרציה סוגרת.
--       ⭐ עבורן `synced_at` הוא הזמן היחיד שנמדד ולא הומצא.
--
-- ⛔ **הסף הוא `1e12` ולא «נראה גדול»** — ⚠️ מילישניות מ-2001 ואילך גדולות
--    ממנו, ⛔ ומספר רץ באפליקציה הזו לא יגיע אליו לעולם.
--
-- ⛔ **אידמפוטנטי** — התנאי הוא `updated_at is null or updated_at = 0`,
--    ⚠️ והרצה חוזרת אינה נוגעת בשורה שכבר נושאת חותמת: ⛔ דריסה של חותמת
--    קיימת הייתה מחזירה נתונים אחורה בשקט.
-- ============================================================================


-- ───────────────────────────────────────────────────────────────────────────
-- א · ה-`id` הוא מילישניות
-- ───────────────────────────────────────────────────────────────────────────
update public.tb_entries
   set updated_at = (data->>'id')::bigint
 where (updated_at is null or updated_at = 0)
   and (data->>'id') ~ '^[0-9]+$'
   and (data->>'id')::bigint >= 1000000000000;


-- ───────────────────────────────────────────────────────────────────────────
-- ב · כל השאר — `synced_at`
-- ───────────────────────────────────────────────────────────────────────────
-- ⚠️ `coalesce` ל-`now()` אינו ויתור: שורה בלי `synced_at` אינה אמורה
--    להתקיים, ⛔ אבל חותמת של עכשיו עדיפה על אפס — ⭐ אפס מפסיד לכל דבר,
--    ⚠️ ו-`now()` מפסיד רק למה שנכתב אחריו.
update public.tb_entries
   set updated_at = (extract(epoch from coalesce(synced_at, now())) * 1000)::bigint
 where updated_at is null or updated_at = 0;


-- ============================================================================
-- ⭐ בדיקת שקילות — ⛔ תנאי למעבר.
-- ============================================================================
-- ⚠️ «עדכנתי שורות» אינו «אין שורות בלי חותמת»: ⛔ תנאי `where` שגוי היה
--    מעדכן אפס שורות ומדווח הצלחה.
do $$
declare n bigint;
begin
  select count(*) into n from public.tb_entries
   where updated_at is null or updated_at = 0;
  if n > 0 then
    raise exception '⛔ % רשומות עדיין בלי חותמת — לעצור ולהבין מה הן', n;
  end if;
end $$;
