-- ============================================================================
-- ⚠️ נתיב חזרה — מה בדיוק צריך להחזיר
-- ============================================================================
-- 1. **בקוד:** `var TB_ARC_UNIFIED = true;` שבאזור שכבת השורות ב-
--    `index.html` → `false`. זה הכל. הקריאה והכתיבה של הארכיון חוזרות
--    ל-`public.tb_archive`, ורשומות היומן ממשיכות כרגיל ב-`tb_entries`
--    (הדגל `archived=false` שלהן אינו מפריע לאיש). לקדם `CACHE_NAME` +
--    `<meta name="app-version">` כדי שהמכשירים יקבלו את החזרה.
-- ⚠️ `TB_ROWS = false` נשאר נתיב החזרה **הרחב יותר** — הוא
--    מחזיר גם את רשומות היומן ל-`kv`. ⛔ אין לבלבל ביניהם: כאן חוזרים
--    שלב אחד, שם חוזרים שניים.
-- 2. **במסד:** ⛔ **אין מה להחזיר.** `tb_archive` לא נגעה, והאפליקציה
--    המשיכה לכתוב אליה כל עוד `TB_ARC_LEGACY_WRITE` דולק — כלומר היא
--    מעודכנת לרגע החזרה. השורות המסומנות ב-`tb_entries` פשוט מפסיקות
--    להיקרא. ⛔ **ואין למחוק אותן «כדי לנקות»** — מחיקה בארגון היא סימון
--    ולא הסרת שורה (כלל ברזל 6 סעיף 1), ול-`anon` ממילא אין `DELETE`.
-- 3. ⚠️ **מה כן ייאבד בחזרה:** סנאפשוט שנכתב בחלון שבו הכתיבה לטבלה
--    המאוחדת הצליחה והכתיבה הכפולה ל-`tb_archive` נכשלה. הוא מסומן ⏳
--    במכשיר שכתב אותו, ותידחף משם בסנכרון הבא. וגם אם לא — בלוק ה-`kv`
-- עדיין מחזיק אותו, כי הכתיבה הכפולה של לא הופסקה.
--
-- ============================================================================
-- ⛔ הפער והטריגר — מחיקת tb_archive
-- ============================================================================
-- ⛔ **מחיקת `public.tb_archive` אינה במיגרציה הזו**, וגם לא הפסקת הכתיבה
--    הכפולה אליה.
-- **הטריגר:** שבועיים של עבודה תקינה על הטבלה המאוחדת — כלומר שתי
-- שאילתות השקילות שלמעלה נקיות ברגע המעבר, «⏳ ממתין לסנכרון» מציג 0
-- בשני המוסדות, והארכיון במסך נראה כמו שנראה לפני.
-- ⚠️ ורק אז, ובסבב ייעודי: קודם מכבים את `TB_ARC_LEGACY_WRITE`, ורק בסבב
-- שאחריו מריצים `drop table public.tb_archive` — ⛔ ולא שניהם באותו סבב,
-- אחרת אין חלון שבו אפשר לגלות טעות ועדיין לחזור. זה אותו נוהל בדיוק
-- שנקבע ב-`003` למחיקת המפתחות הישנים מ-`kv`.
