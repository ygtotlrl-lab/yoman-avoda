-- ============================================================================
-- 005_merge_archive_into_entries.sql — הארכיון עובר לטבלה אחת
-- ============================================================================
--
-- ⛔ **רץ במסד.** ⛔ מיגרציה שכבר רצה אינה נערכת — ⚠️ המסד החיל אותה,
--    ועריכה שלה יוצרת מצב שבו הקובץ מתאר משהו אחר ממה שרץ; ⛔ שינוי מבני
--    נעשה בקובץ הבא בתור.
--
-- ⛔⛔ **תנאי מוקדם, ואין לעקוף אותו:** `002` → `003` → `004` רצו, בסדר הזה.
--     ⚠️ ובפרט `004` — בלי עמודת `archived` ה-`INSERT` שכאן ייכשל, וזה
--     הכישלון הרצוי.
--
-- ── מה הקובץ עושה, ומה הוא **לא** עושה ─────────────────────────────────────
-- ⭐ **אדיטיבי בלבד.** הוא קורא מ-`public.tb_archive` וכותב ל-
--    `public.tb_entries` עם `archived = true`. ⛔ הוא **אינו נוגע**
--    ב-`tb_archive`: אין בו `update`, אין `delete`, אין `truncate` ואין
--    `drop` עליה. היא נשארת במקומה כנתיב חזרה, והאפליקציה ממשיכה לכתוב
--    אליה כל עוד `TB_ARC_LEGACY_WRITE` דולק (ר' `index.html`).
--    מחיקתה **אינה במיגרציה הזו** — ר' «הפער והטריגר» בסוף.
--
-- ⭐ **אידמפוטנטי, ו-`do nothing` ולא `do update`** — אותה החלטה בדיוק
--    כמו ב-`003`, ומאותו נימוק: מרגע שהאפליקציה כותבת לטבלה המאוחדת,
--    השורה שם עשויה להיות **חדשה יותר** מזו שב-`tb_archive` (הכתיבה
--    הכפולה היא best-effort ואינה קובעת את `ok`). `do update` היה דורס
--    אותה בערך ישן יותר — כלומר מחזיר נתונים אחורה בשקט. `do nothing`
--    הופך הרצה חוזרת ל-no-op גמור, ומה שחסר משלים את עצמו בדחיפה הבאה
--    של המכשיר.
--    ⛔ אין להחליף ל-`do update` בשום מצב.
--
-- ⚠️ **מה שאינו מומר, ומדולג ולא מומצא:** שורה ב-`tb_archive` בלי
--    `client_id` אינה קיימת (הוא המפתח הראשי), ולכן אין כאן מקרה מקביל
--    ל«סנאפשוט בלי מזהה» של `003` — הסינון הזה כבר קרה שם.
-- ============================================================================


-- ============================================================================
-- ⛔ שער מקדים — התנגשות מפתחות. **להריץ לפני ה-INSERT.**
-- ============================================================================
-- כל האיחוד נשען על הנחה אחת: מרחב המפתחות של שני הסוגים **זר**.
--   רשומת יומן → `rec_key` = ה-`id` כמחרוזת (מספר).
--   סנאפשוט    → `rec_key` = `'g:'||gdate`, ובהיעדרו `'i:'||id`.
-- ⚠️ ההנחה נכונה לפי `entryKey`/`archiveKey` שב-`index.html` ולפי `003` —
--    אבל היא **הנחה על נתונים**, ולכן היא נבדקת ולא מונחת. התנגשות אחת
--    פירושה שסנאפשוט ורשומת יומן חולקים שורה בטבלה המאוחדת, וזה בדיוק
--    סוג הנזק שאין ממנו חזרה שקטה.
do $$
declare n bigint;
begin
  select count(*) into n
  from public.tb_archive a
  join public.tb_entries e
    on e.yeshiva = a.yeshiva and e.rec_key = a.rec_key
  where e.archived = false;
  if n > 0 then
    raise exception '⛔ % התנגשויות מפתח בין tb_archive ל-tb_entries — לעצור ולהבין מה הן', n;
  end if;
end $$;


-- ───────────────────────────────────────────────────────────────────────────
-- ההעברה עצמה
-- ───────────────────────────────────────────────────────────────────────────
-- ⚠️ `client_id`, `yeshiva` ו-`rec_key` עוברים **כמות שהם**. זו הנקודה
--    שמאפשרת ל-`do nothing` להיות אידמפוטנטי ולנתיב החזרה להיות סימטרי:
--    אותה שורה לוגית נושאת את אותו מזהה בשתי הטבלאות. ⛔ אין לייצר כאן
--    מזהה חדש — הנימוק המלא בראש `002`, סעיף 2.
insert into public.tb_entries
  (client_id, yeshiva, rec_key, gdate, updated_at, deleted, data, archived)
select a.client_id, a.yeshiva, a.rec_key, a.gdate, a.updated_at, a.deleted, a.data, true
from public.tb_archive a
on conflict (client_id) do nothing;


-- ============================================================================
-- ⭐ בדיקת שקילות — שני הכיוונים. ⛔ תנאי למעבר.
-- ============================================================================
-- ⚠️ שקילות **חד-כיוונית אינה שקילות**: «כל שורה מסומנת בטבלה קיימת
--    בארכיון» מתקיים גם כשלא הועברה אף שורה. שני הכיוונים נבדקים, תמיד.
--
-- ⚠️ **והם אינם סימטריים בחומרתם, וזו החלטה ולא השמטה:**
--    • **כיוון א** (שורת ארכיון שלא הגיעה) הוא **אובדן** — הבלוק למטה
--      **זורק** ומגלגל את ה-`INSERT` לאחור.
--    • **כיוון ב** (שורה מסומנת שאין לה מקבילה בארכיון) הוא **עודף**, והוא
--      **אמור לגדול** אחרי שהמערכת חיה: רשומה שנכתבה בזמן שהכתיבה הכפולה
--      ל-`tb_archive` נכשלה תופיע רק בטבלה המאוחדת. לכן הוא מדווח ב-
--      `notice` ולא זורק. ⛔ ובכל זאת **ברגע המעבר הוא חייב להיות 0**, וזה
--      מה שנבדק ידנית בשאילתה שמתחתיו.
--    זו אותה הבחנה בדיוק שנרשמה ב-`003` לגבי `extra_in_table`.
do $$
declare miss bigint; extra bigint;
begin
  select count(*) into miss
  from public.tb_archive a
  left join public.tb_entries e
    on e.client_id = a.client_id and e.archived
  where e.client_id is null;

  select count(*) into extra
  from public.tb_entries e
  left join public.tb_archive a on a.client_id = e.client_id
  where e.archived and a.client_id is null;

  raise notice 'שקילות: כיוון א (חסר בטבלה המאוחדת) = %, כיוון ב (עודף) = %', miss, extra;
  if miss > 0 then
    raise exception '⛔ % שורות ארכיון לא הגיעו לטבלה המאוחדת — המיגרציה מתגלגלת לאחור', miss;
  end if;
end $$;

